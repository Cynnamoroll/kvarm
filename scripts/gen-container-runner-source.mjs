#!/usr/bin/env node
/**
 * Regenerates apps/platform/src/containers/runnerSource.ts: the `kvarm runner`
 * modules from apps/cli/src as strings, so the Container CI runner writes the
 * same claim -> snapshot checkout -> run -> report code into its container
 * that a user runs locally. These modules import only node: builtins,
 * each other, and the RUNNER_PACKAGES files (written in flat).
 *
 *   node scripts/gen-container-runner-source.mjs          write the module
 *   node scripts/gen-container-runner-source.mjs --check  exit 1 when stale
 *
 * scripts/test/containerRunner.test.ts fails when the committed
 * module drifts from apps/cli/src.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const RUNNER_MODULES = ['runner.js', 'executor.js', 'checkout.js', 'workdir.js', 'git.js', 'guards.js', 'http.js', 'untar.js'];
/** @kvarm/* packages the runner modules import, embedded as flat files: specifier -> [local file, source path]. */
export const RUNNER_PACKAGES = { '@kvarm/zstd': ['zstd.js', 'packages/zstd/src/index.js'] };
const LOCAL_FILES = new Set([...RUNNER_MODULES, ...Object.values(RUNNER_PACKAGES).map(([file]) => file)]);
const root = new URL('..', import.meta.url);
export const OUTPUT = fileURLToPath(new URL('apps/platform/src/containers/runnerSource.ts', root));

export function renderRunnerSource() {
  const checkImports = (name, source) => {
    for (const m of source.matchAll(/^import .* from '([^']+)';$/gm)) {
      const spec = m[1];
      if (!spec.startsWith('node:') && !(spec.startsWith('./') && LOCAL_FILES.has(spec.slice(2)))) {
        throw new Error(`${name} imports ${spec}, which the container runner does not carry`);
      }
    }
  };
  const entries = RUNNER_MODULES.map((name) => {
    let source = readFileSync(new URL(`apps/cli/src/${name}`, root), 'utf8');
    for (const [specifier, [file]] of Object.entries(RUNNER_PACKAGES)) {
      source = source.replaceAll(`'${specifier}'`, `'./${file}'`);
    }
    checkImports(name, source);
    return `  ${JSON.stringify(name)}: ${JSON.stringify(source)},`;
  });
  for (const [file, path] of Object.values(RUNNER_PACKAGES)) {
    const source = readFileSync(new URL(path, root), 'utf8');
    checkImports(file, source);
    entries.push(`  ${JSON.stringify(file)}: ${JSON.stringify(source)},`);
  }
  return [
    '// Generated by scripts/gen-container-runner-source.mjs from apps/cli/src; do not edit.',
    '// The `kvarm runner` modules the Container CI runner writes into its container.',
    'export const RUNNER_MODULES: Record<string, string> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = renderRunnerSource();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(OUTPUT, 'utf8');
    } catch {}
    if (current !== next) {
      console.error(`${OUTPUT} is stale; run node scripts/gen-container-runner-source.mjs`);
      process.exit(1);
    }
    console.log('runnerSource.ts is current');
  } else {
    writeFileSync(OUTPUT, next);
    console.log(`wrote ${OUTPUT}`);
  }
}
